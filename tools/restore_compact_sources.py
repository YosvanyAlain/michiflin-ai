#!/usr/bin/env python3
"""Recreate the two omitted XZ duplicates in an extracted source delivery.

The complete historical gzip sources remain in the source ZIP. Regeneration
uses only those local bytes and Python's standard library, verifies the exact
committed hashes, and never overwrites an existing file. A different liblzma
version can produce different compressed bytes; a differing output is not
published, and the exact file must be obtained from the matching repository
commit instead. This tool never touches account state or the historical gzip.
"""
from __future__ import annotations

import gzip
import hashlib
import lzma
import os
from pathlib import Path
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    ("source-7zip-26.05", "989c658cef4c13124ed1f4ff7330a6ce5ab22cefdbbc9daae9b2c110dde9a63b",
     "6f00ec0dd7bfca88fa29e9b4bde149eac79dd4ef59f26d53fc767c595c2a9ae1",
     "8a566c3cfa56f20c8541a399e0af296feb2989fae2aa3ee9bf19fa3847d64f60"),
    ("source-wrapper-26.5.0", "6c1dde0beddc27c82dcff32021e914af99d575b3b96d7ee0d87f55b462ac2d71",
     "3b23c0499c19ce7ec367b9d8ddf1856d67c39cf446d70d8cc58ae46a02fa7184",
     "4958de9f9f460df0df4084a76b1ca00e8031412fb999e4b406c69860e7080aec"),
)


def digest(path: Path) -> str:
    result = hashlib.sha256()
    with path.open("rb") as source:
        while chunk := source.read(1024 * 1024):
            result.update(chunk)
    return result.hexdigest()


def _valid_file(path: Path, expected: str) -> bool:
    return not path.is_symlink() and path.is_file() and digest(path) == expected


def restore(root: Path = ROOT) -> int:
    folder = root / "webxdc" / "vendor" / "7zip"
    made = 0
    for stem, gzip_hash, tar_hash, xz_hash in SOURCES:
        source, target = folder / f"{stem}.tar.gz", folder / f"{stem}.tar.xz"
        if target.exists() or target.is_symlink():
            if not _valid_file(target, xz_hash):
                raise ValueError(f"existing output differs; not overwritten: {target.name}")
            continue
        if not _valid_file(source, gzip_hash):
            raise ValueError(f"historical source missing or changed: {source.name}")
        fd, name = tempfile.mkstemp(prefix=".compact-source-", suffix=".part", dir=folder)
        temporary = Path(name)
        try:
            os.close(fd)
            raw_hash = hashlib.sha256()
            size = 0
            with gzip.open(source, "rb") as original, lzma.open(
                    temporary, "wb", format=lzma.FORMAT_XZ, preset=9 | lzma.PRESET_EXTREME) as compact:
                while chunk := original.read(1024 * 1024):
                    size += len(chunk)
                    if size > 100_000_000:
                        raise ValueError("unexpected source size")
                    raw_hash.update(chunk)
                    compact.write(chunk)
            if raw_hash.hexdigest() != tar_hash or digest(temporary) != xz_hash:
                raise ValueError(f"regenerated bytes differ: {target.name}; use files from the matching commit")
            try:
                # Same directory and atomic no-overwrite publication. If another
                # process wins the race, accept only exactly the expected bytes.
                os.link(temporary, target)
                made += 1
            except FileExistsError:
                if not _valid_file(target, xz_hash):
                    raise ValueError(f"concurrent output differs; not overwritten: {target.name}") from None
        finally:
            temporary.unlink(missing_ok=True)
    return made


if __name__ == "__main__":
    try:
        print(f"Verified compact source files; recreated: {restore()}")
    except (OSError, ValueError, EOFError, lzma.LZMAError) as exc:
        print(f"Compact source restoration stopped safely: {exc}")
        raise SystemExit(1)
